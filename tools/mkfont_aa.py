#!/usr/bin/env python3
"""Build anti-aliased 8x16 coverage fonts in the CP866 layout.

Output: kernel/fontaa.c with two coverage tables (regular + bold),
256 glyphs x 16 rows x 8 columns of 0..255 ink coverage. The cell
geometry is identical to the VGA bitmap font (8x16), so every layout
in the kernel keeps working - only the edges get smooth.

Rasterisation: DejaVu Sans Mono (full Cyrillic) rendered at 3x and
box-downsampled. Glyphs DejaVu does not have fall back to the legacy
bitmap font (parsed from kernel/font8x16.c) expanded to coverage.

    python3 tools/mkfont_aa.py [--preview font-preview.png]
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SS = 3                      # supersampling factor
CELL_W, CELL_H = 8, 16
FONT_SIZE = 13 * SS         # em size at supersample scale
BASELINE = 13 * SS          # baseline y at supersample scale (tunable)
REGULAR = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
BOLD = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'


def legacy_bitmap():
    """Parse the 1-bit font out of kernel/font8x16.c: 256x16 bytes."""
    text = (ROOT / 'kernel/font8x16.c').read_text()
    text = re.sub(r'/\*.*?\*/', '', text)   # keep /* 0xNN */ row tags out
    vals = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', text)]
    rows = vals[:256 * 16]
    return [rows[i * 16:(i + 1) * 16] for i in range(256)]


def render_glyph(font, ch, notdef_mask):
    """Render one character into an 8x16 coverage list (row-major)."""
    big = Image.new('L', (CELL_W * SS, CELL_H * SS), 0)
    d = ImageDraw.Draw(big)
    # DejaVu Sans Mono advance is 0.602em; at FONT_SIZE=39 that is
    # 23.5px, a hair under the 24px supersampled cell - centre it.
    d.text((CELL_W * SS // 2, BASELINE), ch, font=font, fill=255,
           anchor='ms')
    mask = font.getmask(ch)
    if mask.getbbox() is None:
        return None
    import io
    m1 = Image.new('L', (mask.size[0] or 1, mask.size[1] or 1))
    m1.putdata(list(mask))
    m2 = Image.new('L', (notdef_mask.size[0] or 1, notdef_mask.size[1] or 1))
    m2.putdata(list(notdef_mask))
    if m1.size == m2.size and list(m1.getdata()) == list(m2.getdata()):
        return None                      # .notdef box -> missing glyph
    small = big.resize((CELL_W, CELL_H), Image.BOX)
    return list(small.getdata())


def build(path):
    font = ImageFont.truetype(path, FONT_SIZE)
    notdef = font.getmask('\uFFFF')
    legacy = legacy_bitmap()
    glyphs = []
    for idx in range(256):
        ch = bytes([idx]).decode('cp866', errors='replace')
        cov = None
        if ch not in ('\ufffd',) and ord(ch) >= 0x20:
            try:
                cov = render_glyph(font, ch, notdef)
            except Exception:
                cov = None
        if cov is None:
            cov = []
            for rowbits in legacy[idx]:
                for col in range(8):
                    cov.append(255 if rowbits & (0x80 >> col) else 0)
        glyphs.append(cov)
    return glyphs


def emit(name, glyphs, out):
    """Coverage packed 4 bits per pixel (16 levels): 64 bytes per glyph."""
    out.append(f'const u8 {name}[256 * 16 * 4] = {{')
    for idx, cov in enumerate(glyphs):
        vals = []
        for r in range(16):
            for pair in range(4):
                hi = cov[r * 8 + pair * 2] >> 4
                lo = cov[r * 8 + pair * 2 + 1] >> 4
                vals.append((hi << 4) | lo)
        out.append(f'    /* 0x{idx:02X} */ ' +
                   ' '.join(f'0x{v:02X},' for v in vals))
    out.append('};')
    out.append('')


def preview(glyphs, path):
    sample = ('KvantOS 3.1.4 "Photon" 0123456789\n'
              'Графическая среда: окна, иконки, меню\n'
              'АБВГДЕЖЗ абвгдежз Ёё № § <> [] {} ()\n'
              'The quick brown fox -> C:\\KvantOS\\sdk\n'
              '┌─┬─┐ │├─┼─┤ └─┴─┘ █▓▒░ ●')
    lines = sample.split('\n')
    img = Image.new('RGB', (8 * 40 * 3, 16 * len(lines) * 3), (16, 24, 48))
    for li, line in enumerate(lines):
        for ci, ch in enumerate(line[:40]):
            idx = ch.encode('cp866', errors='replace')[0]
            cov = glyphs[idx]
            for r in range(16):
                for c in range(8):
                    v = cov[r * 8 + c]
                    px = tuple(16 + (240 - 16) * v // 255 for _ in range(3))
                    for dy in range(3):
                        for dx in range(3):
                            img.putpixel((ci * 24 + c * 3 + dx,
                                          li * 48 + r * 3 + dy), px)
    img.save(path)
    print('preview ->', path)


def main():
    out = ['/* Generated by tools/mkfont_aa.py - anti-aliased 8x16 coverage',
           ' * font (DejaVu Sans Mono, CP866 layout). Do not edit by hand. */',
           '#include "kernel.h"', '']
    reg = build(REGULAR)
    emit('kv_font_aa', reg, out)
    if '--with-bold' in sys.argv:
        emit('kv_font_aa_bold', build(BOLD), out)
    target = ROOT / 'kernel/fontaa.c'
    target.write_text('\n'.join(out))
    print('wrote', target, f'({target.stat().st_size} bytes)')
    if '--preview' in sys.argv:
        preview(reg, sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()
